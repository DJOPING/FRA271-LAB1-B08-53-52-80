% =========================================================================
% สคริปต์รับค่าจาก Simulink และคำนวณค่าเฉลี่ย 3 รอบ (3 Runs)
% =========================================================================

%Vth = 1.1 V = 2.2 - 1.1

% --- ขั้นตอนที่ 1: บันทึกค่าแต่ละรอบหลังกด Run Simulink ---
% % (หลังจากรัน Simulink รอบที่ 1 เสร็จแล้ว ให้รันบรรทัดนี้)
% run1_data = out.v_data; 
% 
% % (หลังจากหมุนแกนใหม่ แล้วรัน Simulink รอบที่ 2 เสร็จแล้ว ให้รันบรรทัดนี้)
% run2_data = out.v_data; 
% 
% % (หลังจากหมุนแกนใหม่ แล้วรัน Simulink รอบที่ 3 เสร็จแล้ว ให้รันบรรทัดนี้)
% run3_data = out.v_data; 


% --- ขั้นตอนที่ 2: สคริปต์ดึงช่วง 5 วินาทีค่านิ่ง และคำนวณค่าเฉลี่ยสุทธิ ---
% ดึงเฉพาะค่าแรงดัน (Data) ออกจาก Timeseries
v1_raw = run1_data.Data;
v2_raw = run2_data.Data;
v3_raw = run3_data.Data;

% กำหนดจำนวน Sample ช่วงค่านิ่ง 5 วินาทีท้ายสุด (เช่น 500 Samples)
N = 500; 

% ดึงเฉพาะช่วงท้ายมาหาค่าเฉลี่ยของแต่ละรอบ (ได้ค่านิ่งค่าเดียว)
V1 = mean(v1_raw(end-N:end)); % ค่า V1 ของรอบที่ 1
V2 = mean(v2_raw(end-N:end)); % ค่า V2 ของรอบที่ 2
V3 = mean(v3_raw(end-N:end)); % ค่า V3 ของรอบที่ 3

% คำนวณค่าเฉลี่ยรวม (Mean) และค่าความเที่ยงตรง (Std Dev)
V_avg = mean([V1, V2, V3]);
V_std = std([V1, V2, V3]);

% แสดงผลลัพธ์ใน Command Window
fprintf('\n=======================================\n');
fprintf('ผลการทดลอง 3 รอบ (ค่าเฉลี่ยช่วงนิ่ง 5 วินาที):\n');
fprintf('  รอบที่ 1 (V1) = %.4f V\n', V1);
fprintf('  รอบที่ 2 (V2) = %.4f V\n', V2);
fprintf('  รอบที่ 3 (V3) = %.4f V\n', V3);
fprintf('---------------------------------------\n');
fprintf('>> ค่าเฉลี่ยรวม 3 รอบ (V_avg) = %.4f V\n', V_avg);
fprintf('>> Standard Deviation (Std)   = %.4f V\n', V_std);
fprintf('=======================================\n');
% 
% 
% =======================================
% ผลการทดลอง 3 รอบ (ค่าเฉลี่ยช่วงนิ่ง 5 วินาที):
%   รอบที่ 1 (V1) = 2.7314 V
%   รอบที่ 2 (V2) = 2.7209 V
%   รอบที่ 3 (V3) = 2.7310 V
% ---------------------------------------
% ค่าเฉลี่ยรวม 3 รอบ (V_avg) = 2.7277 V
% Standard Deviation (Std)   = 0.0060 V
% =======================================